"""Convert samples into system/user/assistant messages.

Reuse `tools/data_process/format.py`, the single source of truth for training,
evaluation, and RL, to construct user text and keep evaluation messages exactly
aligned with the training sequence layout:

    system  = format.SYSTEM_PROMPT
    user    = {joined memory_docs}\\n\\n{format.user_*(dataset, ...)}
    assistant= generated by the backend

Memory and query share one user turn, matching tokenize_train.py:110. In state
mode, the vLLM engine handles chunk eviction; evaluation does not build an
eviction schedule itself.
"""
from __future__ import annotations

import json
import os
import re
import sys
from dataclasses import dataclass

# format.py lives under tools/data_process; add that path before importing it,
# as in tokenize_train.py.
_FMT_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "tools", "data_process")
if _FMT_DIR not in sys.path:
    sys.path.insert(0, _FMT_DIR)
import format as F  # noqa: E402

from .datasets import DatasetCfg  # noqa: E402

# Separator between memory documents, matching token-mode training in
# tokenize_train.py.
MEM_SEP = "\n\n"


@dataclass
class Request:
    """One model call: a message group plus metadata required for judging."""
    id: str
    messages: list[dict]
    kind: str               # single / multi / ttl; selects answer extraction.
    questions: list[str]
    golds: list[list[str]]  # Gold aliases for each question, used by the judge.
    group_id: str           # Requests sharing a memory/pack form one accuracy group.
    memory_docs: list[str] | None = None
    user_text: str | None = None
    cats: list | None = None  # Per-question categories for official F1 metrics.


def _qa_list(row: dict) -> list[dict]:
    qa = row["qa"]
    return json.loads(qa) if isinstance(qa, str) else qa


def _golds(qa_item: dict) -> list[str]:
    a = qa_item.get("answer")
    if a is None:
        return []
    return list(a) if isinstance(a, list) else [a]


_LABEL_RE = re.compile(r"(?mi)^label:\s*(\d+)")


def _label_set(memory_docs: list[str]) -> list[int]:
    """Parse sorted candidate labels from ICL memory's ``label: N`` lines."""
    nums = {int(m.group(1)) for d in memory_docs for m in _LABEL_RE.finditer(d)}
    return sorted(nums)


def _messages(memory_docs: list[str], user_text: str) -> list[dict]:
    mem = MEM_SEP.join(memory_docs)
    return [
        {"role": "system", "content": F.SYSTEM_PROMPT},
        {"role": "user", "content": f"{mem}{MEM_SEP}{user_text}"},
    ]


def build_requests(cfg: DatasetCfg, row: dict, reason: bool = False) -> list[Request]:
    """Convert one processed row into one or more requests.

    - ``kind=single``: expand each QA item into an independent single-question
      request; test_single normally has one question per row.
    - ``kind=multi``: pack the row's full QA list into one multi-question request.
    - `reason` controls whether the instruction elicits chain-of-thought. It is
      False by default to match the SFT distribution and the instruct model's
      natural behavior. Enable it for RL checkpoints trained with reason=True.
    """
    if cfg.kind == "official_single":  # Official Delta-Mem/MAB prompt protocol.
        from .official_prompt import build_official_requests
        return build_official_requests(cfg, row, Request, _qa_list, _golds)
    md, qa = row["memory_docs"], _qa_list(row)
    rid = row["id"]
    if cfg.drop_cats:  # Exclude LoCoMo cat5 without changing source data.
        qa = [q for q in qa if q.get("category") not in cfg.drop_cats]
        if not qa:
            return []
    cats = ([q.get("category") for q in qa]
            if any(q.get("category") is not None for q in qa) else None)
    prompt_name = cfg.prompt_name or cfg.name
    if cfg.kind in {"multi", "ttl_multi", "recsys_multi"}:
        questions = [q["question"] for q in qa]
        if cfg.kind == "ttl_multi":
            labels = _label_set(md)
            user_text = F.user_ttl(prompt_name, questions, labels, reason=reason)
            extract_kind = "ttl"
        elif cfg.kind == "recsys_multi":
            user_text = F.user_recsys_multi(prompt_name, questions, reason=reason)
            extract_kind = "multi"
        else:
            user_text = F.user_multi(prompt_name, questions, reason=reason)
            extract_kind = "multi"
        return [Request(rid, _messages(md, user_text), extract_kind, questions,
                        [_golds(q) for q in qa], group_id=rid,
                        memory_docs=md, user_text=user_text, cats=cats)]
    # Expand single and ttl_single per question; both use the single-answer
    # extraction protocol with an ``Answer:`` prefix.
    labels = _label_set(md) if cfg.kind == "ttl_single" else None
    out = []
    for i, q in enumerate(qa):
        if cfg.kind == "ttl_single":
            user_text = F.user_ttl_single(prompt_name, q["question"], labels, reason=reason)
        elif cfg.kind == "recsys_single":
            user_text = F.user_recsys_single(prompt_name, q["question"], reason=reason)
        else:
            user_text = F.user_single(prompt_name, q["question"], reason=reason)
        out.append(Request(f"{rid}#{i}", _messages(md, user_text), "single",
                           [q["question"]], [_golds(q)], group_id=rid,
                           memory_docs=md, user_text=user_text,
                           cats=[cats[i]] if cats else None))
    return out
